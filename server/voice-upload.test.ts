import fs from 'node:fs'
import path from 'node:path'
import { beforeEach,afterAll,expect,it,vi } from 'vitest'
const mock=vi.hoisted(()=>({transcribe:vi.fn()}))
vi.mock('./transcribe.ts',()=>({ARCHIVE_DIR:path.join(process.env.HOME!,'voice-upload-test'),transcribe:mock.transcribe,openaiKey:()=>null}))
const root=path.join(process.env.HOME!,'voice-upload-test')
beforeEach(()=>{fs.rmSync(root,{recursive:true,force:true});mock.transcribe.mockReset()})
afterAll(()=>fs.rmSync(root,{recursive:true,force:true}))
const chunk=(s:string)=>Buffer.from(s).toString('base64')
it('shares concurrent finish and replays the persisted result after restart without another provider call',async()=>{
 const {addChunk,finishUpload}=await import('./voicepipe.ts')
 let complete!:(text:string)=>void
 mock.transcribe.mockImplementation(()=>new Promise<string>(resolve=>{complete=resolve}))
 addChunk('voice-one',0,'audio/mp4',chunk('first'))
 addChunk('voice-one',1,'audio/mp4',chunk('last'))
 const a=finishUpload('voice-one','en',2),b=finishUpload('voice-one','en',2)
 await Promise.resolve()
 expect(mock.transcribe).toHaveBeenCalledTimes(1)
 expect(mock.transcribe.mock.calls[0][0].toString()).toBe('firstlast')
 complete('The full transcript');expect(await a).toBe('The full transcript');expect(await b).toBe(await a)
 vi.resetModules()
 const reloaded=await import('./voicepipe.ts')
 reloaded.addChunk('voice-one',0,'audio/mp4',chunk('first'))
 reloaded.addChunk('voice-one',1,'audio/mp4',chunk('last'))
 expect(await reloaded.finishUpload('voice-one','en',2)).toBe('The full transcript')
 expect(mock.transcribe).toHaveBeenCalledTimes(1)
 await expect(reloaded.finishUpload('voice-one','en',3)).rejects.toThrow()
 expect(()=>reloaded.addChunk('voice-one',0,'audio/mp4',chunk('changed'))).toThrow()
 expect(()=>reloaded.addChunk('voice-one',0,'audio/webm',chunk('first'))).toThrow()
 expect(()=>reloaded.addChunk('voice-one',1,'audio/webm',chunk('last'))).toThrow()
 expect(()=>reloaded.addChunk('voice-one',2,'audio/mp4',chunk('new tail'))).toThrow()
 expect(fs.readFileSync(path.join(root,'partial','voice-one','type'),'utf8')).toBe('audio/mp4')
 expect(fs.readFileSync(path.join(root,'partial','voice-one','0000001'),'utf8')).toBe('last')
})
it('refuses missing chunks and a missing tail before creating any provider job; disk chunks survive reload',async()=>{
 let api=await import('./voicepipe.ts')
 api.addChunk('voice-gap',0,'audio/mp4',chunk('first'))
 api.addChunk('voice-gap',2,'audio/mp4',chunk('last'))
 await expect(api.finishUpload('voice-gap','en',3)).rejects.toThrow()
 expect(mock.transcribe).not.toHaveBeenCalled()
 vi.resetModules();api=await import('./voicepipe.ts')
 api.addChunk('voice-gap',1,'audio/mp4',chunk('middle'))
 await expect(api.finishUpload('voice-gap','en',4)).rejects.toThrow()
 mock.transcribe.mockResolvedValue('Recovered')
 expect(await api.finishUpload('voice-gap','en',3)).toBe('Recovered')
 expect(mock.transcribe.mock.calls[0][0].toString()).toBe('firstmiddlelast')
})
it('preserves all bytes after failure and never resubmits an unconfirmed previous outcome',async()=>{
 const api=await import('./voicepipe.ts')
 api.addChunk('voice-failure',0,'audio/mp4',chunk('precious audio'))
 mock.transcribe.mockRejectedValue(new Error('Connection lost'))
 await expect(api.finishUpload('voice-failure','en',1)).rejects.toThrow('Connection lost')
 vi.resetModules();const reloaded=await import('./voicepipe.ts')
 await expect(reloaded.finishUpload('voice-failure','en',1)).rejects.toThrow()
 expect(mock.transcribe).toHaveBeenCalledTimes(1)
 expect(fs.readFileSync(path.join(root,'partial','voice-failure','0000000'),'utf8')).toBe('precious audio')
})
